"""Writes the gateway's configuration and runs it as a child process.

The gateway (our Open Edison fork) listens on 127.0.0.1 only. Agents reach it
through the console's authenticated /mcp/{key}/ proxy, which signs each
request with the agent's identity.
"""

from __future__ import annotations

import asyncio
import json
import os
import sys
from pathlib import Path
from typing import Any

from countersign.settings import Secrets, Settings

REPO_ROOT = Path(__file__).resolve().parent.parent

# How each tool counts toward Open Edison's lethal trifecta.
COUNTERSIGN_TOOLS: dict[str, dict[str, Any]] = {
    "refund_payment": {
        "write_operation": True,
        "read_private_data": False,
        "read_untrusted_public_data": False,
        "acl": "PRIVATE",
    },
    "send_payout": {"write_operation": True, "read_private_data": False, "read_untrusted_public_data": False, "acl": "PRIVATE"},
    "get_payment": {"write_operation": False, "read_private_data": True, "read_untrusted_public_data": False, "acl": "PRIVATE"},
    "check_money_move": {
        "write_operation": False,
        "read_private_data": False,
        "read_untrusted_public_data": False,
        "acl": "PUBLIC",
    },
}
DEMO_SHOP_TOOLS: dict[str, dict[str, Any]] = {
    "list_tickets": {"write_operation": False, "read_private_data": False, "read_untrusted_public_data": True, "acl": "PUBLIC"},
    "read_ticket": {"write_operation": False, "read_private_data": False, "read_untrusted_public_data": True, "acl": "PUBLIC"},
    "lookup_order": {"write_operation": False, "read_private_data": True, "read_untrusted_public_data": False, "acl": "PRIVATE"},
}


def child_env(settings: Settings) -> dict[str, str]:
    """Environment for processes the gateway starts. stdio servers do not inherit the parent's."""
    env = {
        "COUNTERSIGN_BACKEND": settings.backend,
        "COUNTERSIGN_DATA_DIR": str(settings.data_dir),
        "COUNTERSIGN_APPROVAL_TIMEOUT": str(settings.approval_timeout_s),
        "PYTHONUNBUFFERED": "1",
    }
    if settings.backend == "sandbox":
        env["PAYPAL_CLIENT_ID"] = settings.paypal_client_id
        env["PAYPAL_CLIENT_SECRET"] = settings.paypal_client_secret
    return env


def write_gateway_config(settings: Settings, secrets: Secrets) -> Path:
    gateway_dir = settings.gateway_dir
    gateway_dir.mkdir(parents=True, exist_ok=True)
    servers: list[dict[str, Any]] = [
        {
            "name": "countersign",
            "command": sys.executable,
            "args": ["-m", "countersign.money_server"],
            "env": child_env(settings),
            "enabled": True,
        }
    ]
    permissions: dict[str, Any] = {
        "_metadata": {"description": "Generated by Countersign on every start", "last_updated": "generated"},
        "countersign": {name: {"enabled": True, **perm} for name, perm in COUNTERSIGN_TOOLS.items()},
    }
    if settings.demo_shop:
        servers.append(
            {
                "name": "shop",
                "command": sys.executable,
                "args": [str(REPO_ROOT / "demo" / "shop_server.py")],
                "env": child_env(settings),
                "enabled": True,
            }
        )
        permissions["shop"] = {name: {"enabled": True, **perm} for name, perm in DEMO_SHOP_TOOLS.items()}

    config = {
        "server": {"host": "127.0.0.1", "port": settings.gateway_mcp_port, "api_key": secrets.gateway_api_key},
        "logging": {"level": "INFO"},
        "telemetry": {"enabled": False},
        "mcp_servers": servers,
    }
    _write_private(gateway_dir / "config.json", config)
    _write_private(gateway_dir / "tool_permissions.json", permissions)
    for name in ("resource_permissions.json", "prompt_permissions.json"):
        _write_private(gateway_dir / name, {"_metadata": {"description": "Generated by Countersign"}})
    (gateway_dir / ".setup_tui_ran").touch()
    return gateway_dir


def _write_private(path: Path, data: dict[str, Any]) -> None:
    path.write_text(json.dumps(data, indent=2) + "\n")
    path.chmod(0o600)


async def start_gateway(settings: Settings, secrets: Secrets) -> asyncio.subprocess.Process:
    gateway_dir = write_gateway_config(settings, secrets)
    env = {
        **os.environ,
        **child_env(settings),
        "OPEN_EDISON_CONFIG_DIR": str(gateway_dir),
        "COUNTERSIGN_GATEWAY_SECRET": secrets.gateway_secret,
        "COUNTERSIGN_HIDE_BUILTINS": "1",
        "OTEL_SDK_DISABLED": "true",
    }
    log_file = (settings.data_dir / "gateway.log").open("ab")
    return await asyncio.create_subprocess_exec(
        sys.executable,
        "-m",
        "src",
        "--config-dir",
        str(gateway_dir),
        cwd=str(settings.data_dir),
        env=env,
        stdin=asyncio.subprocess.DEVNULL,
        stdout=log_file,
        stderr=log_file,
    )
